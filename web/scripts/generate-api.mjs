import { compileFromFile } from "json-schema-to-typescript";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const schemaPath = `${root}/src/api/schema.json`;
const outputPath = `${root}/src/api/types.gen.ts`;
const header = "// Generated by pnpm gen:api. Do not edit by hand.\n\n";
const generated = await compileFromFile(schemaPath, {
  bannerComment: "",
  format: true,
  style: { singleQuote: false, semi: true, tabWidth: 2, trailingComma: "all" },
  unreachableDefinitions: true,
});
const expected = `${header}${generated}`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== expected) {
    console.error("src/api/types.gen.ts is stale; run make web-gen");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, expected);
}
